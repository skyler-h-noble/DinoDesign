/**
 * componentThemes.js is generated here: every component the package exports,
 * rendered with no props (and again with `open`), and the data-theme values
 * that appear in the document recorded. The Vite plugin keeps those themes
 * for any app that imports the component, so a theme a component picks on its
 * own is never trimmed.
 *
 *   UPDATE_COMPONENT_THEMES=1 npx react-scripts test src/vite/componentThemes --watchAll=false
 *
 * rewrites the file. Without the flag the test fails when the file is stale.
 */
import React from 'react';
import { writeFileSync } from 'fs';
import { join } from 'path';
import { render, cleanup } from '@testing-library/react';
import * as Lib from '../components';
import { COMPONENT_THEMES } from './componentThemes';

const THEMES = ['Primary', 'Secondary', 'Tertiary', 'Neutral', 'Info', 'Success', 'Warning', 'Error', 'App-Bar', 'Nav-Bar', 'Status'];

function themesRendered(Comp, props) {
  const seen = new Set();
  const origError = console.error;
  const origWarn = console.warn;
  console.error = () => {};
  console.warn = () => {};
  try {
    render(React.createElement(Comp, props, 'x'));
    document.querySelectorAll('[data-theme]').forEach((el) => {
      const t = el.getAttribute('data-theme');
      if (THEMES.includes(t)) seen.add(t);
    });
  } catch (e) {
    /* A component that needs props to render shows nothing without them —
       whatever theme it then uses comes from those props, which the app's
       own literals carry. */
  } finally {
    cleanup();
    console.error = origError;
    console.warn = origWarn;
  }
  return seen;
}

function generate() {
  const out = {};
  for (const [name, Comp] of Object.entries(Lib).sort(([a], [b]) => a.localeCompare(b))) {
    if (!/^[A-Z]/.test(name)) continue;
    const isComponent = typeof Comp === 'function' || (Comp && typeof Comp === 'object' && Comp.$$typeof);
    if (!isComponent) continue;
    const seen = new Set([...themesRendered(Comp, {}), ...themesRendered(Comp, { open: true })]);
    if (seen.size) out[name] = THEMES.filter((t) => seen.has(t));
  }
  return out;
}

function source(map) {
  return `/* Generated by componentThemes.test.js — do not edit by hand.
   Themes each component renders with no props (or with \`open\`). Default is
   always kept and is not listed. */
export const COMPONENT_THEMES = ${JSON.stringify(map, null, 2)};
`;
}

test('componentThemes.js matches what the components render', () => {
  const map = generate();
  if (process.env.UPDATE_COMPONENT_THEMES) {
    writeFileSync(join(__dirname, 'componentThemes.js'), source(map));
    return;
  }
  expect(COMPONENT_THEMES).toEqual(map);
}, 120000);
