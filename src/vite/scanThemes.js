/**
 * Which themes an app uses — read from its source at build time, so the Vite
 * plugin can link only those themes' mode files (themeHead.selectModeParts).
 *
 * A theme is counted when:
 *   1. it is Default — the page root wears it, always;
 *   2. a string literal in the app's code names it — "Primary", "error",
 *      'warning-outline', `nav-bar` — whatever prop or attribute carries it
 *      (data-theme, theme, color, variant). Case-insensitive; a literal that
 *      starts with the name and a dash counts too;
 *   3. a lib component the app imports renders it with no props
 *      (componentThemes.js, generated by rendering every component).
 *
 * It is deliberately generous: a literal "info" in a log call keeps the Info
 * theme. Keeping a theme costs ~10 KB compressed; dropping one that is used
 * costs its colors. Names the code builds at run time are invisible here —
 * the provider links those on sight, and `themes: [...]` on the plugin keeps
 * any the app wants up front.
 *
 * Node only.
 */
import { readdirSync, readFileSync, statSync } from 'fs';
import { join, extname } from 'path';
import { COMPONENT_THEMES } from './componentThemes';

export const SOURCE_EXTENSIONS = ['.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs', '.mdx', '.md', '.html', '.vue', '.svelte', '.astro'];
const SKIP_DIRS = new Set(['node_modules', 'dist', 'build', '.git', 'coverage', '.next', '.vite', '.turbo', '.cache', 'out']);

const LITERAL = /(["'`])((?:\\.|(?!\1)[^\\\n])*)\1/g;
const LIB_IMPORT = /import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*['"]@omni-design\/components(?:\/[\w-]+)?['"]/g;

/** Themes named by a string literal in `text`. */
export function themesInSource(text, names) {
  const lower = names.map((n) => [n, n.toLowerCase()]);
  const found = new Set();
  for (const m of text.matchAll(LITERAL)) {
    const v = m[2].trim().toLowerCase();
    if (!v || v.length > 40) continue;
    for (const [name, low] of lower) {
      if (v === low || v.startsWith(low + '-')) found.add(name);
    }
  }
  return found;
}

/** Lib components imported by name in `text`. */
export function importedComponents(text) {
  const out = new Set();
  for (const m of text.matchAll(LIB_IMPORT)) {
    m[1].split(',').forEach((part) => {
      const name = part.trim().split(/\s+as\s+/)[0].replace(/^type\s+/, '').trim();
      if (name) out.add(name);
    });
  }
  return out;
}

function walk(dir, files) {
  let entries;
  try { entries = readdirSync(dir); } catch (e) { return; }
  for (const name of entries) {
    if (SKIP_DIRS.has(name) || name.startsWith('.')) continue;
    const p = join(dir, name);
    let st;
    try { st = statSync(p); } catch (e) { continue; }
    if (st.isDirectory()) walk(p, files);
    else if (SOURCE_EXTENSIONS.includes(extname(name))) files.push(p);
  }
}

/**
 * The themes an app at `root` uses, in the system's order.
 *   names   the system's theme names (modeParts.order)
 *   extra   themes to keep regardless (the plugin's `themes` option)
 * Returns { themes, files, fromLiterals, fromComponents }.
 */
export function scanAppThemes(root, names, { extra = [], componentThemes = COMPONENT_THEMES } = {}) {
  const files = [];
  walk(root, files);
  const fromLiterals = new Set();
  const components = new Set();
  for (const f of files) {
    let text;
    try { text = readFileSync(f, 'utf8'); } catch (e) { continue; }
    themesInSource(text, names).forEach((t) => fromLiterals.add(t));
    importedComponents(text).forEach((c) => components.add(c));
  }
  const fromComponents = new Set();
  components.forEach((c) => (componentThemes[c] || []).forEach((t) => fromComponents.add(t)));
  const want = new Set(['Default', ...fromLiterals, ...fromComponents, ...extra]);
  return {
    themes: names.filter((n) => want.has(n)),
    files: files.length,
    fromLiterals: [...fromLiterals],
    fromComponents: [...fromComponents],
  };
}
